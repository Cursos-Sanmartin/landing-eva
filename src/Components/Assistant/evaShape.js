const f = (v) => v.toFixed(2);

// Ceja: una curva más gruesa del lado de adentro de la cara
export function browPath(b, raise, tilt) {
  const half = b.len / 2;
  const y = b.cy - raise;
  let yL = y;
  let yR = y;
  if (b.innerRight) {
    yR -= tilt;
    yL += tilt * 0.3;
  } else {
    yL -= tilt;
    yR += tilt * 0.3;
  }
  const xL = b.cx - half;
  const xR = b.cx + half;
  const qx = b.cx;
  const qy = (yL + yR) / 2 - b.arch;
  const top = [];
  const bot = [];
  for (let i = 0; i <= 10; i++) {
    const u = i / 10;
    const iu = 1 - u;
    const x = iu * iu * xL + 2 * iu * u * qx + u * u * xR;
    const yy = iu * iu * yL + 2 * iu * u * qy + u * u * yR;
    const dx = 2 * iu * (qx - xL) + 2 * u * (xR - qx);
    const dy = 2 * iu * (qy - yL) + 2 * u * (yR - qy);
    const l = Math.hypot(dx, dy) || 1;
    const nx = -dy / l;
    const ny = dx / l;
    const w = b.innerRight ? 2.2 + 4.4 * u : 6.6 - 4.4 * u;
    top.push(f(x + (nx * w) / 2) + " " + f(yy + (ny * w) / 2));
    bot.push(f(x - (nx * w) / 2) + " " + f(yy - (ny * w) / 2));
  }
  return "M" + top.join("L") + "L" + bot.reverse().join("L") + "Z";
}

// Boca calada en la base de la v: labio de arriba y de abajo como dos curvas
export function mouthGeo(w, o, s, k, dx) {
  const cx = MOUTH.x + dx;
  const l = cx - w / 2;
  const r = cx + w / 2;
  const yl = MOUTH.y - s * 2.6 - k;
  const yr = MOUTH.y - s * 2.6 + k;
  const up = MOUTH.y + s * 2;
  const lo = up + o * 15;
  const d =
    "M" + f(l) + " " + f(yl) + "Q" + f(cx) + " " + f(up) + " " + f(r) + " " + f(yr) +
    "Q" + f(cx) + " " + f(lo) + " " + f(l) + " " + f(yl) + "Z";
  const bottom = (yl + yr) / 4 + lo / 2;
  return { d, cx: f(cx), ty: f(bottom - 0.6), rx: f(w * 0.28), ry: f(Math.max(0, o * 3.6)) };
}
